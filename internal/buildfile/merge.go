package buildfile

import (
	"fmt"
	"sort"
	"strings"
)

// ChangeKind classifies a planned edit.
type ChangeKind string

const (
	Added    ChangeKind = "add"
	Removed  ChangeKind = "remove"
	Replaced ChangeKind = "replace"
)

// Change is one planned edit, described by the node key.
type Change struct {
	Kind ChangeKind `json:"kind"`
	Key  string     `json:"key"`
}

// Note is something Sprout deliberately did not change, with the snippet a
// user may want to apply by hand.
type Note struct {
	Key     string `json:"key"`
	Message string `json:"message"`
	Snippet string `json:"snippet,omitempty"`
}

// Plan is the result of a merge.
type Plan struct {
	Changes []Change `json:"changes"`
	Notes   []Note   `json:"notes,omitempty"`
	// Result is the new build file content.
	Result string `json:"-"`
}

// Changed reports whether the plan modifies the file.
func (p *Plan) Changed() bool { return len(p.Changes) > 0 }

type edit struct {
	start, end int
	text       string
	order      int
}

type merger struct {
	user, a, b *Doc
	userUnit   string
	refUnit    string
	edits      []edit
	plan       *Plan
}

// Merge applies to user the difference between reference documents a (the
// project's current dependencies) and b (with the requested change). Both
// references must be generated by Spring Initializr for the same project
// settings. Nodes are matched by key:
//
//   - nodes only in b are inserted (after their nearest preceding sibling),
//     unless the user already has them;
//   - nodes only in a are removed when the user's copy is unmodified (or is a
//     dependency with the same coordinates);
//   - nodes that differ between a and b are replaced when the user's copy
//     matches a.
//
// Anything else is reported as a Note and left untouched.
func Merge(user, a, b *Doc) (*Plan, error) {
	if user.Kind != a.Kind || a.Kind != b.Kind {
		return nil, fmt.Errorf("build kinds differ: %s, %s, %s", user.Kind, a.Kind, b.Kind)
	}
	m := &merger{user: user, a: a, b: b, userUnit: user.indentUnit(), refUnit: b.indentUnit(), plan: &Plan{}}
	m.merge(user.Root, a.Root, b.Root)
	res, err := m.apply()
	if err != nil {
		return nil, err
	}
	if _, err := Parse(user.Kind, res); err != nil {
		return nil, fmt.Errorf("internal error: edited build file does not parse (%w); nothing was changed", err)
	}
	m.plan.Result = res
	return m.plan, nil
}

func (m *merger) note(key, msg, snippet string) {
	m.plan.Notes = append(m.plan.Notes, Note{Key: key, Message: msg, Snippet: snippet})
}

func (m *merger) change(kind ChangeKind, key string) {
	m.plan.Changes = append(m.plan.Changes, Change{Kind: kind, Key: key})
}

// merge reconciles container u (user) with a -> b. a may be nil (empty).
func (m *merger) merge(u, a, b *Node) {
	empty := &Node{Container: true}
	if a == nil {
		a = empty
	}
	if b == nil {
		b = empty
	}
	for i, bc := range b.Children {
		ac := a.Child(bc.Key)
		uc := u.Child(bc.Key)
		switch {
		case ac == nil && uc == nil:
			m.insert(u, b, i)
		case ac == nil && bc.Container && uc.Container:
			m.merge(uc, nil, bc)
		case ac == nil:
			if !bc.KeyOnly && m.user.normalize(uc) != m.b.normalize(bc) {
				m.note(bc.Key, "already exists with different content; review it manually", m.b.Text(bc))
			}
		case m.a.normalize(ac) == m.b.normalize(bc):
			// unchanged between references
		case uc == nil:
			if !bc.KeyOnly {
				m.note(bc.Key, "is missing from your build file; Spring Initializr would now generate", m.b.Text(bc))
			}
		case bc.Container && uc.Container:
			m.merge(uc, ac, bc)
		case m.user.normalize(uc) == m.a.normalize(ac):
			m.replace(uc, bc)
		case !bc.KeyOnly:
			m.note(bc.Key, "was customized, so it was not updated; Spring Initializr would now generate", m.b.Text(bc))
		}
	}
	for _, ac := range a.Children {
		if b.Child(ac.Key) != nil {
			continue
		}
		for _, uc := range u.childrenWithKey(ac.Key) {
			switch {
			case uc.KeyOnly || m.user.normalize(uc) == m.a.normalize(ac):
				m.remove(uc)
			case uc.Container && ac.Container:
				m.merge(uc, ac, nil)
			default:
				m.note(ac.Key, "is no longer needed but was customized, so it was kept", "")
			}
		}
	}
}

// topLevel reports whether container c is the Gradle root, whose statements
// are separated by blank lines.
func (m *merger) topLevel(c *Node) bool { return m.user.Kind != Maven && c == m.user.Root }

// insert adds b.Children[i] into user container u.
func (m *merger) insert(u, b *Node, i int) {
	bc := b.Children[i]
	src := m.user.Src
	var anchor *Node
	for j := i - 1; j >= 0 && anchor == nil; j-- {
		anchor = u.Child(b.Children[j].Key)
	}
	indent := m.childIndent(u)
	text := reindent(m.b.Text(bc), m.b.indentOf(bc), m.refUnit, indent, m.userUnit)
	sep := "\n"
	if m.topLevel(u) {
		sep = "\n\n"
	}
	switch {
	case anchor != nil:
		pos := lineEnd(src, anchor.End)
		m.add(pos, pos, sep[1:]+"\n"+indent+text, Added, bc.Key)
	case len(u.Children) > 0:
		pos := m.user.attachedStart(u.Children[0])
		m.add(pos, pos, indent+text+sep, Added, bc.Key)
	default:
		closeLine := lineStart(src, u.CloseStart)
		if strings.TrimSpace(src[closeLine:u.CloseStart]) == "" && closeLine > u.Start {
			m.add(closeLine, closeLine, indent+text+"\n", Added, bc.Key)
		} else {
			m.add(u.CloseStart, u.CloseStart, "\n"+indent+text+"\n"+m.user.indentOf(u), Added, bc.Key)
		}
	}
}

// childIndent is the indentation for children of container u.
func (m *merger) childIndent(u *Node) string {
	for _, c := range u.Children {
		if m.user.ownsLines(c) {
			return m.user.indentOf(c)
		}
	}
	if u == m.user.Root && m.user.Kind != Maven {
		return ""
	}
	return m.user.indentOf(u) + m.userUnit
}

func (m *merger) remove(n *Node) {
	src := m.user.Src
	if !m.user.ownsLines(n) {
		m.add(n.Start, n.End, "", Removed, n.Key)
		return
	}
	start := lineStart(src, n.Start)
	end := lineEnd(src, n.End)
	if end < len(src) {
		end++
	}
	// Avoid leaving two blank lines where a top-level block was removed.
	if m.user.Kind != Maven && start > 0 && end < len(src) && src[end] == '\n' {
		prev := lineStart(src, start-1)
		if strings.TrimSpace(src[prev:start]) == "" {
			end++
		}
	}
	m.add(start, end, "", Removed, n.Key)
}

func (m *merger) replace(u, b *Node) {
	text := reindent(m.b.Text(b), m.b.indentOf(b), m.refUnit, m.user.indentOf(u), m.userUnit)
	m.add(u.Start, u.End, text, Replaced, u.Key)
}

func (m *merger) add(start, end int, text string, kind ChangeKind, key string) {
	m.edits = append(m.edits, edit{start: start, end: end, text: text, order: len(m.edits)})
	m.change(kind, key)
}

func (m *merger) apply() (string, error) {
	edits := append([]edit(nil), m.edits...)
	sort.SliceStable(edits, func(i, j int) bool {
		ei, ej := edits[i], edits[j]
		if ei.start != ej.start {
			return ei.start > ej.start
		}
		// At the same offset, apply deletions before insertions so inserted
		// text is never consumed by a deletion, and insert later edits first
		// so earlier ones end up in front.
		if (ei.end > ei.start) != (ej.end > ej.start) {
			return ei.end > ei.start
		}
		return ei.order > ej.order
	})
	src := m.user.Src
	limit := len(src) + 1
	for _, e := range edits {
		if e.end > limit {
			return "", fmt.Errorf("internal error: overlapping edits")
		}
		src = src[:e.start] + e.text + src[e.end:]
		limit = e.start
	}
	return src, nil
}
